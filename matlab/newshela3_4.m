%% ============================================================
% 9. Different initial-condition tests
%% ============================================================

x0_case_1 = zeros(6,1);

% beta(0) = 1 deg
x0_case_2 = [ ...
    deg2rad(1);
    0;
    0;
    0;
    0;
    0];

% p(0) = 1 deg/s and phi(0) = -5 deg
x0_case_3 = [ ...
    0;
    deg2rad(1);
    0;
    deg2rad(-5);
    0;
    0];

% delta_a(0) = 1 deg
x0_case_4 = [ ...
    0;
    0;
    0;
    0;
    deg2rad(1);
    0];

initial_conditions = [ ...
    x0_case_1, ...
    x0_case_2, ...
    x0_case_3, ...
    x0_case_4];

case_names = [ ...
    "Zero initial state";
    "beta(0) = 1 deg";
    "p(0) = 1 deg/s, phi(0) = -5 deg";
    "delta_a(0) = 1 deg"];

number_of_cases = size(initial_conditions,2);

phi_cases = zeros(length(t),number_of_cases);
delta_a_cases = zeros(length(t),number_of_cases);
delta_c_cases = zeros(length(t),number_of_cases);

FinalPhi = zeros(number_of_cases,1);
MaxDeltaA = zeros(number_of_cases,1);
MaxDeltaC = zeros(number_of_cases,1);
MeetsAileronLimit = false(number_of_cases,1);

for k = 1:number_of_cases

    x_aug_case = lsim( ...
        sys_aug_states, ...
        r, ...
        t, ...
        initial_conditions(:,k));

    phi_cases(:,k) = ...
        rad2deg(x_aug_case(:,4));

    delta_a_cases(:,k) = ...
        rad2deg(x_aug_case(:,5));

    delta_c_cases(:,k) = ...
        rad2deg(-x_aug_case*K_aug.');

    FinalPhi(k) = ...
        phi_cases(end,k);

    MaxDeltaA(k) = ...
        max(abs(delta_a_cases(:,k)));

    MaxDeltaC(k) = ...
        max(abs(delta_c_cases(:,k)));

    MeetsAileronLimit(k) = ...
        MaxDeltaA(k) <= aileron_limit_deg;
end

InitialConditionResults = table( ...
    case_names, ...
    FinalPhi, ...
    MaxDeltaA, ...
    MaxDeltaC, ...
    MeetsAileronLimit, ...
    'VariableNames',{ ...
    'InitialCondition', ...
    'FinalPhiDeg', ...
    'MaxDeltaADeg', ...
    'MaxDeltaCDeg', ...
    'MeetsAileronLimit'});

disp(' ')
disp('Initial-condition test results:')
disp(InitialConditionResults)

