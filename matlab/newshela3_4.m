%% ============================================================
% Question 3(d)
% Stationary Linear Quadratic Servo Controller
%% ============================================================

clear
close all
clc

%% ============================================================
% 1. Aircraft model
%
% State vector:
% x = [beta  p  r  phi  delta_a]'
%% ============================================================

A = [ ...
    -0.575     0       -1       0.0536   -0.078;
    -300      -3.03     2       0        64.4;
      68       0.045   -2.4     0         5;
       0       1        0       0         0;
       0       0        0       0        -5];

B = [0; 0; 0; 0; 5];

C_phi = [0 0 0 1 0];

n = size(A,1);

%% ============================================================
% 2. Augmented servo model
%
% xi_dot = phi_c - phi
% xa = [x; xi]
%% ============================================================

A_aug = [ ...
    A,              zeros(n,1);
   -C_phi,          0];

B_aug = [B; 0];

% Reference input enters the integral-state equation
E_ref = [zeros(n,1); 1];

%% Augmented controllability check

Co_aug = ctrb(A_aug,B_aug);
rank_Co_aug = rank(Co_aug);

fprintf('Augmented controllability rank = %d\n', ...
    rank_Co_aug)

if rank_Co_aug ~= n+1
    error('The augmented system is not completely controllable.')
end

%% ============================================================
% 3. LQ Servo design
%% ============================================================

Q = diag([ ...
    0.1, ...      % beta
    0.001, ...    % p
    0.001, ...    % r
    10, ...       % phi
    0.001, ...    % delta_a
    100]);        % integral tracking error

R = 100;

% K_aug  - LQ feedback gain
% P_riccati - solution of the algebraic Riccati equation
% poles_lqr - closed-loop poles
[K_aug,P_riccati,poles_lqr] = ...
    lqr(A_aug,B_aug,Q,R);

poles_lqr = poles_lqr(:);

A_cl = A_aug-B_aug*K_aug;

K_x = K_aug(1:5);
K_i = K_aug(6);

%% ============================================================
% 4. Verification of the Riccati equation
%
% A'P + PA - PBR^(-1)B'P + Q = 0
%% ============================================================

riccati_residual = ...
    A_aug'*P_riccati ...
    + P_riccati*A_aug ...
    - P_riccati*B_aug*(R\B_aug')*P_riccati ...
    + Q;

riccati_error = norm(riccati_residual,'fro');

K_check = R\(B_aug'*P_riccati);
gain_error = norm(K_aug-K_check);

fprintf('\n============================================\n')
fprintf('LQ SERVO DESIGN\n')
fprintf('============================================\n')

fprintf('\nLQ gain K_aug:\n')
disp(K_aug)

fprintf('State-feedback part K_x:\n')
disp(K_x)

fprintf('Integral gain K_i:\n')
fprintf('K_i = %.8f\n',K_i)

fprintf('\nRiccati residual norm = %.4e\n', ...
    riccati_error)

fprintf('Gain verification error = %.4e\n', ...
    gain_error)

fprintf('\nClosed-loop poles:\n')
disp(poles_lqr)

%% ============================================================
% 5. Closed-loop systems
%% ============================================================

% Output all six augmented states
sys_aug_states = ss( ...
    A_cl, ...
    E_ref, ...
    eye(n+1), ...
    zeros(n+1,1));

% Output roll angle phi only
C_phi_aug = [C_phi 0];

sys_phi = ss( ...
    A_cl, ...
    E_ref, ...
    C_phi_aug, ...
    0);

sys_phi.Name = 'LQ Servo';

%% ============================================================
% 6. Nominal 30-degree command simulation
%% ============================================================

phi_command_deg = 30;
phi_command_rad = deg2rad(phi_command_deg);

t = (0:0.001:10)';
r = phi_command_rad*ones(size(t));

x_aug_0 = zeros(n+1,1);

x_aug_response = lsim( ...
    sys_aug_states, ...
    r, ...
    t, ...
    x_aug_0);

%% Separate the states

x = x_aug_response(:,1:5);
x_i = x_aug_response(:,6);

phi_deg = rad2deg(x(:,4));
delta_a_deg = rad2deg(x(:,5));

%% Control command

% delta_c = -K_aug*x_aug
delta_c_rad = -x_aug_response*K_aug.';
delta_c_deg = rad2deg(delta_c_rad);

%% Tracking error

tracking_error_deg = ...
    phi_command_deg-phi_deg;

%% ============================================================
% 7. Performance calculations
%% ============================================================

phi_final_deg = ...
    phi_command_deg*real(dcgain(sys_phi));

steady_state_error_deg = ...
    phi_command_deg-phi_final_deg;

info = stepinfo( ...
    phi_deg, ...
    t, ...
    phi_command_deg, ...
    'SettlingTimeThreshold',0.02);

[max_delta_a,index_delta_a] = ...
    max(abs(delta_a_deg));

[max_delta_c,index_delta_c] = ...
    max(abs(delta_c_deg));

aileron_limit_deg = 5;

meets_aileron_limit = ...
    max_delta_a <= aileron_limit_deg;

fprintf('\n============================================\n')
fprintf('NOMINAL LQ SERVO PERFORMANCE\n')
fprintf('============================================\n')

fprintf('Final phi = %.8f deg\n', ...
    phi_final_deg)

fprintf('Steady-state error = %.8e deg\n', ...
    steady_state_error_deg)

fprintf('Rise time = %.4f s\n', ...
    info.RiseTime)

fprintf('Settling time = %.4f s\n', ...
    info.SettlingTime)

fprintf('Overshoot = %.4f %%\n', ...
    info.Overshoot)

fprintf('Max |delta_a| = %.4f deg\n', ...
    max_delta_a)

fprintf('Max |delta_c| = %.4f deg\n', ...
    max_delta_c)

fprintf('Aileron limit satisfied = %d\n', ...
    meets_aileron_limit)

Results = table( ...
    phi_final_deg, ...
    steady_state_error_deg, ...
    info.RiseTime, ...
    info.SettlingTime, ...
    info.Overshoot, ...
    max_delta_a, ...
    max_delta_c, ...
    meets_aileron_limit, ...
    'VariableNames',{ ...
    'FinalPhiDeg', ...
    'SteadyStateErrorDeg', ...
    'RiseTimeSec', ...
    'SettlingTimeSec', ...
    'OvershootPercent', ...
    'MaxDeltaADeg', ...
    'MaxDeltaCDeg', ...
    'MeetsAileronLimit'});

disp(' ')
disp('LQ Servo results:')
disp(Results)

%% ============================================================
% 8. Pole and zero information
%% ============================================================

closed_loop_poles = pole(sys_phi);
closed_loop_zeros = zero(sys_phi);

fprintf('\nClosed-loop damping information:\n')
damp(sys_phi)

fprintf('\nClosed-loop poles:\n')
